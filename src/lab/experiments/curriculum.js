/* =========================================================
   HELPERS
========================================================= */

export function getGradeCurriculum(
  grade
) {

  return (
    CURRICULUM[
      Number(
        grade
      )
    ] ||
    null
  )

}


export function getLessonById(
  grade,
  lessonId
) {

  const curriculum =
    getGradeCurriculum(
      grade
    )


  if (!curriculum) {
    return null
  }


  for (
    const chapter of
    curriculum.chapters
  ) {

    const lesson =
      chapter.lessons.find(
        item =>
          item.id ===
          lessonId
      )


    if (
      lesson
    ) {

      return {

        ...lesson,

        chapterId:
          chapter.id,

        chapterTitle:
          chapter.title

      }

    }

  }


  return null

}